function packById(id) {
  return PACKS.find((p) => p.id === id) || null;
}

// Every theme of the chosen packs at the chosen rating, tagged with its pack
// so a card on screen can say where it came from. A pack of the wrong
// rating is silently ignored: this function is the age filter.
function themesOf(rating, packIds) {
  const out = [];
  const seen = new Set();
  packIds.forEach((id) => {
    const pack = packById(id);
    if (!pack || pack.rating !== rating) return;
    pack.themes.forEach((text) => {
      if (seen.has(text)) return;
      seen.add(text);
      out.push({ text, pack: pack.id });
    });
  });
  return out;
}

// What a lobby needs to offer the packs: no themes, just the shelf.
function catalog() {
  return PACKS.map((p) => ({
    id: p.id, rating: p.rating, emoji: p.emoji, title: p.title, size: p.themes.length,
  }));
}

module.exports = {
  RATINGS, PACKS, EVENTS, packsFor, packById, themesOf, catalog,
};
